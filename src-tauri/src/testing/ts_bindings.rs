//! The TypeScript types of the commands' arguments and results, generated from their serde
//! structs (ts-rs, which follows the serde attributes) into `src/lib/tauri/generated/`, where
//! the wrappers in `src/lib/tauri` import them. `cargo test` rewrites the folder; CI fails when
//! it differs from what is committed, so a renamed field, a new variant or a changed `Option`
//! breaks the build instead of the webview.
//!
//! A command taking or returning a new struct or enum: derive `ts_rs::TS` on it (`#[ts(rename)]`
//! when the frontend knows it by another name) and list it below. The types it uses come along.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use ts_rs::{Config, TS};

use crate::app::operations;
use crate::machine::tools;
use crate::{account, cloud, error, machine, runtime, shared_folder, terminal};

const HEADER: &str = "// Generated by `cargo test` (src-tauri/src/testing/ts_bindings.rs). Do not edit by hand.\n";

/// Brings `dir` up to date with every command type (and the types they use), and an `index.ts`
/// re-exporting them all: generated into a folder of their own first, then only the files that
/// changed are written into `dir` and the ones no longer generated removed (a removed or renamed
/// type leaves no file behind), so a `tsc` or `eslint` running meanwhile never misses a file.
fn export(dir: &Path) {
    let staged = std::env::temp_dir().join(format!("cyberctf-ts-bindings-{}", rand::random::<u64>()));
    generate(&staged);
    sync(&staged, dir);
    fs::remove_dir_all(&staged).unwrap();
}

/// Writes every command type and the index into `dir`, a new folder.
fn generate(dir: &Path) {
    fs::create_dir_all(dir).unwrap();
    // serde_json reads a u64 into a JS number, not a bigint.
    let cfg = Config::new().with_out_dir(dir).with_large_int("number");
    macro_rules! export {
        ($($t:ty),* $(,)?) => {
            $( <$t>::export_all(&cfg).unwrap_or_else(|e| panic!("exporting {}: {e}", stringify!($t))); )*
        };
    }
    export!(
        account::agent::AgentInfo,
        account::agent::LaunchRequest,
        account::api_operation::ApiOperation,
        account::auth::AuthStatus,
        account::auth::DeviceCode,
        cloud::AzureSubscription,
        cloud::Cloud,
        cloud::GcpBillingAccount,
        cloud::GcpOrganization,
        cloud::OciConfig,
        error::Wire,
        machine::selftest::Kind,
        machine::storage::Storage,
        machine::system::SystemReport,
        machine::system::metrics::MachineMetrics,
        machine::workloads::Workload,
        operations::ActiveOperation,
        tools::install::Dependency,
        tools::ovftool::Outcome,
        tools::uninstall::InstalledTool,
        runtime::Check,
        runtime::AttackStatus,
        runtime::LabStatus,
        runtime::Park,
        runtime::Preview,
        runtime::Runtime,
        runtime::lab::Observer,
        runtime::lab::Requirements,
        runtime::lab::RunOptions,
        runtime::start_place::StartPlace,
        runtime::selftest_report::Event,
        runtime::lab::Resources,
        runtime::providers::Provider,
        crate::commands::app::ManagedSettings,
        runtime::server::capacity::HostCapacity,
        runtime::server::HostInput,
        crate::commands::server::HostList,
        runtime::server::HostProfile,
        runtime::server::TestResult,
        runtime::proxmox::placement::Placement,
        shared_folder::SharedFolderInfo,
        terminal::TermEvent,
    );
    write_provider_names(dir);
    write_selftest_steps(dir);
    write_deploy_log(dir);
    write_index(dir);
}

/// The file of the steps each server's VM test reports ([`runtime::server_selftest::PLANS`]),
/// which the Server screen lists up front (not a type: imported by its path, not from the index).
fn write_selftest_steps(dir: &Path) {
    let entries = runtime::server_selftest::PLANS.iter().fold(String::new(), |mut lines, (provider, steps)| {
        let steps = steps.iter().map(|s| format!("\"{s}\"")).collect::<Vec<_>>().join(", ");
        let _ = writeln!(lines, "  {}: [{steps}],", provider.id());
        lines
    });
    let doc = "/** The steps each server's VM test reports, in order, by provider (Rust's `server_selftest::PLANS`). */";
    fs::write(dir.join(format!("{SELFTEST_STEPS}.ts")), format!("{HEADER}\n{doc}\nexport const SELFTEST_STEPS = {{\n{entries}}} as const;\n")).unwrap();
}

/// The generated file of the VM test's steps (a value, not a type).
const SELFTEST_STEPS: &str = "SelfTestSteps";

/// The file of how the launcher's own deploy-log lines start, by the step the lab page files them
/// under ([`runtime::deploy_log`]), which the page's step parser reads (not a type: imported by
/// its path, not from the index).
fn write_deploy_log(dir: &Path) {
    use runtime::deploy_log::{DONE_MARK, FAILED_MARK, FETCH, PREPARE};
    let listed = |starts: &[&str]| starts.iter().map(|s| serde_json::to_string(s).unwrap()).collect::<Vec<_>>().join(", ");
    let doc_fetch = "/** How the launcher's lines start while it fetches and places the lab: the \"Download the lab\" step (Rust's `deploy_log::FETCH`). */";
    let doc_prepare = "/** How the launcher's lines start while it readies this machine for a lab's VMs: the \"Prepare this machine\" step when one\n *  comes first (Rust's `deploy_log::PREPARE`). */";
    let marks = format!(
        "/** How a failed run's closing line starts (Rust's `deploy_log::FAILED_MARK`). */\nexport const FAILED_MARK = {};\n\n/** How a run's closing line starts when it went through (Rust's `deploy_log::DONE_MARK`). */\nexport const DONE_MARK = {};\n",
        serde_json::to_string(FAILED_MARK).unwrap(),
        serde_json::to_string(DONE_MARK).unwrap(),
    );
    let text = format!(
        "{HEADER}\n{marks}\n{doc_fetch}\nexport const FETCH_LINES: readonly string[] = [{}];\n\n{doc_prepare}\nexport const PREPARE_LINES: readonly string[] = [{}];\n",
        listed(&FETCH),
        listed(&PREPARE),
    );
    fs::write(dir.join(format!("{DEPLOY_LOG}.ts")), text).unwrap();
}

/// The generated file of the deploy log's line starts (values, not types).
const DEPLOY_LOG: &str = "DeployLog";

/// The file of every provider's name as the player reads it ([`Provider::label`]), the one table
/// the webview names providers from (not a type: imported by its path, not from the index).
fn write_provider_names(dir: &Path) {
    use runtime::providers::Provider;
    let entries = Provider::ALL.iter().chain(&Provider::CLOUDS).fold(String::new(), |mut lines, p| {
        let _ = writeln!(lines, "  {}: \"{}\",", p.id(), p.label());
        lines
    });
    let doc = "/** Each provider's name as the player reads it (Rust's `Provider::label`). */";
    // The names an OS changes (Rust's `Provider::label_on`), by OS.
    let on = ["macos", "linux", "windows"].iter().fold(String::new(), |mut lines, os| {
        let names = Provider::ALL.iter().filter(|p| p.label_on(os) != p.label()).fold(String::new(), |mut l, p| {
            let _ = write!(l, " {}: \"{}\",", p.id(), p.label_on(os));
            l
        });
        let _ = writeln!(lines, "  {os}: {{{names} }},");
        lines
    });
    let ids = |keep: fn(&Provider) -> bool| Provider::ALL.iter().filter(|p| keep(p)).map(|p| format!("\"{}\"", p.id())).collect::<Vec<_>>().join(", ");
    let doc_local = "/** The hypervisors that run on this machine (Rust's providers that aren't `is_remote`). */";
    let doc_emulators = "/** The hypervisors that run VMs built for another CPU, emulated (Rust's `Provider::is_emulator`). */";
    let doc_servers = "/** The player's own servers, as opposed to cloud accounts, in the launcher's order (Rust's `Provider::SERVERS`). */";
    let listed = |providers: &[Provider]| providers.iter().map(|p| format!("\"{}\"", p.id())).collect::<Vec<_>>().join(", ");
    let (servers, clouds) = (listed(&Provider::SERVERS), listed(&Provider::CLOUDS));
    let doc_clouds = "/** The cloud accounts labs run in, in the launcher's order (Rust's `Provider::CLOUDS`). */";
    let doc_on = "/** The names an OS changes (Rust's `Provider::label_on`): VMware's desktop hypervisor is Fusion on\n *  macOS and Workstation elsewhere. */";
    let text = format!(
        "{HEADER}import type {{ Provider }} from \"./Provider\";\n\n{doc}\nexport const PROVIDER_NAMES: Record<Provider, string> = {{\n{entries}}};\n\n{doc_on}\nexport const PROVIDER_NAMES_ON: Record<string, Partial<Record<Provider, string>>> = {{\n{on}}};\n\n{doc_local}\nexport const LOCAL_PROVIDERS: readonly Provider[] = [{}];\n\n{doc_emulators}\nexport const EMULATORS: readonly Provider[] = [{}];\n\n{doc_servers}\nexport const SERVER_PROVIDERS = [{servers}] as const satisfies readonly Provider[];\n\n{doc_clouds}\nexport const CLOUD_PROVIDERS = [{clouds}] as const satisfies readonly Provider[];\n",
        ids(|p| !p.is_remote()),
        ids(|p| p.is_emulator()),
    );
    fs::write(dir.join(format!("{PROVIDER_NAMES}.ts")), text).unwrap();
}

/// The generated file of provider names (a value, not a type).
const PROVIDER_NAMES: &str = "ProviderNames";

/// The `.ts` files in `dir` (none when it doesn't exist), by name.
fn ts_files(dir: &Path) -> Vec<std::ffi::OsString> {
    let Ok(entries) = fs::read_dir(dir) else { return Vec::new() };
    entries.map(|e| e.unwrap().path()).filter(|p| p.extension().is_some_and(|e| e == "ts")).map(|p| p.file_name().unwrap().to_owned()).collect()
}

/// Makes `dir`'s `.ts` files those of `staged`: a file whose content differs (or is missing) is
/// written, one `staged` hasn't is removed, the others are left alone. Returns the names it
/// wrote or removed.
fn sync(staged: &Path, dir: &Path) -> Vec<std::ffi::OsString> {
    fs::create_dir_all(dir).unwrap();
    let wanted = ts_files(staged);
    let mut changed = Vec::new();
    for name in &wanted {
        let content = fs::read(staged.join(name)).unwrap();
        if fs::read(dir.join(name)).ok().as_ref() != Some(&content) {
            fs::write(dir.join(name), content).unwrap();
            changed.push(name.clone());
        }
    }
    for stale in ts_files(dir).into_iter().filter(|n| !wanted.contains(n)) {
        fs::remove_file(dir.join(&stale)).unwrap();
        changed.push(stale);
    }
    changed
}

/// Writes `index.ts`, re-exporting every generated file.
fn write_index(dir: &Path) {
    let mut names: Vec<String> = fs::read_dir(dir)
        .unwrap()
        .filter_map(|e| e.unwrap().path().file_stem().map(|s| s.to_string_lossy().into_owned()))
        .filter(|n| n != "index" && n != PROVIDER_NAMES && n != SELFTEST_STEPS && n != DEPLOY_LOG)
        .collect();
    names.sort();
    let lines = names.iter().fold(String::new(), |mut lines, n| {
        let _ = writeln!(lines, "export type * from \"./{n}\";");
        lines
    });
    fs::write(dir.join("index.ts"), format!("{HEADER}{lines}")).unwrap();
}

#[test]
fn the_generated_typescript_types_are_written() {
    export(&Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/tauri/generated"));
}

#[test]
fn only_changed_files_are_written_and_stale_ones_removed() {
    let root = std::env::temp_dir().join(format!("cyberctf-ts-sync-{}", rand::random::<u64>()));
    let (staged, dir) = (root.join("staged"), root.join("generated"));
    fs::create_dir_all(&staged).unwrap();
    fs::create_dir_all(&dir).unwrap();
    for (name, text) in [("Same.ts", "same"), ("Changed.ts", "new"), ("Added.ts", "added")] {
        fs::write(staged.join(name), text).unwrap();
    }
    for (name, text) in [("Same.ts", "same"), ("Changed.ts", "old"), ("Gone.ts", "gone"), ("notes.md", "kept")] {
        fs::write(dir.join(name), text).unwrap();
    }
    let mut changed: Vec<String> = sync(&staged, &dir).into_iter().map(|n| n.into_string().unwrap()).collect();
    changed.sort();
    assert_eq!(changed, ["Added.ts", "Changed.ts", "Gone.ts"], "the unchanged file is never rewritten");
    let mut left: Vec<String> = fs::read_dir(&dir).unwrap().map(|e| e.unwrap().file_name().into_string().unwrap()).collect();
    left.sort();
    assert_eq!(left, ["Added.ts", "Changed.ts", "Same.ts", "notes.md"]);
    assert_eq!(fs::read_to_string(dir.join("Changed.ts")).unwrap(), "new");
    assert!(sync(&staged, &dir).is_empty(), "nothing to do the second time");
    fs::remove_dir_all(root).unwrap();
}
