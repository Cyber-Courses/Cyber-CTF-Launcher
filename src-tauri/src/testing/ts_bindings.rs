//! The TypeScript types of the commands' arguments and results, generated from their serde
//! structs (ts-rs, which follows the serde attributes) into `src/lib/tauri/generated/`, where
//! the wrappers in `src/lib/tauri` import them. `cargo test` rewrites the folder; CI fails when
//! it differs from what is committed, so a renamed field, a new variant or a changed `Option`
//! breaks the build instead of the webview.
//!
//! A command taking or returning a new struct or enum: derive `ts_rs::TS` on it (`#[ts(rename)]`
//! when the frontend knows it by another name) and list it below. The types it uses come along.

use std::fs;
use std::path::Path;

use ts_rs::{Config, TS};

use crate::labs::operations;
use crate::machine::tools;
use crate::{account, cloud, error, machine, runtime, shared_folder, terminal};

const HEADER: &str = "// Generated by `cargo test` (src-tauri/src/testing/ts_bindings.rs). Do not edit by hand.\n";

/// Writes every command type (and the types they use) into `dir`, then an `index.ts` re-exporting
/// them all. Clears the folder first, so a removed or renamed type leaves no file behind.
fn export(dir: &Path) {
    clear(dir);
    // serde_json reads a u64 into a JS number, not a bigint.
    let cfg = Config::new().with_out_dir(dir).with_large_int("number");
    macro_rules! export {
        ($($t:ty),* $(,)?) => {
            $( <$t>::export_all(&cfg).unwrap_or_else(|e| panic!("exporting {}: {e}", stringify!($t))); )*
        };
    }
    export!(
        account::agent::AgentInfo,
        account::api_operation::ApiOperation,
        account::auth::AuthStatus,
        cloud::AzureSubscription,
        cloud::Cloud,
        cloud::GcpBillingAccount,
        cloud::GcpOrganization,
        cloud::OciConfig,
        error::Wire,
        machine::selftest::Event,
        machine::selftest::Kind,
        machine::storage::Storage,
        machine::system::SystemReport,
        machine::system::metrics::MachineMetrics,
        machine::workloads::Workload,
        operations::ActiveOperation,
        tools::install::Dependency,
        tools::uninstall::InstalledTool,
        runtime::Check,
        runtime::ExegolStatus,
        runtime::LabStatus,
        runtime::Park,
        runtime::Preview,
        runtime::Runtime,
        runtime::ShellKind,
        runtime::lab::Observer,
        runtime::providers::Provider,
        runtime::server::HostCapacity,
        runtime::server::HostInput,
        runtime::server::HostList,
        runtime::server::HostProfile,
        runtime::server::TestResult,
        shared_folder::SharedFolderInfo,
        terminal::TermEvent,
    );
    write_index(dir);
}

/// Removes the `.ts` files a previous run wrote.
fn clear(dir: &Path) {
    if !dir.exists() {
        return;
    }
    for entry in fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|e| e == "ts") {
            fs::remove_file(path).unwrap();
        }
    }
}

/// Writes `index.ts`, re-exporting every generated file.
fn write_index(dir: &Path) {
    let mut names: Vec<String> =
        fs::read_dir(dir).unwrap().filter_map(|e| e.unwrap().path().file_stem().map(|s| s.to_string_lossy().into_owned())).filter(|n| n != "index").collect();
    names.sort();
    let lines: String = names.iter().map(|n| format!("export type * from \"./{n}\";\n")).collect();
    fs::write(dir.join("index.ts"), format!("{HEADER}{lines}")).unwrap();
}

#[test]
fn the_generated_typescript_types_are_written() {
    export(&Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/tauri/generated"));
}
