//! Cloud-services labs (runtime `CLOUD`): no machines, but cloud services (IAM users, functions,
//! buckets, instances...) from a Terraform module of the lab's own (`cloud:` in its
//! `isoloom.yml`, Isoloom's `cloud-services` target), applied into the player's cloud account.
//!
//! They reuse what the other cloud labs have: the player's cloud account of the lab's cloud
//! (its credentials, region and auto-stop), the host Terraform, the AWS budget guard, and the
//! state kept under `<app data>/deployments/<lab>/<cloud>/`, outside the lab folder, with a run
//! record whose `expires_at` the reaper (`reap_expired_labs`) destroys the lab at. What differs:
//!
//! - The module is the lab's, used as is (see `terraform::services`), with Isoloom's
//!   generated `terraform.tfvars.json` (the spec's fixed `cloud.vars`).
//! - Variables written `{{ inputs.NAME }}` take launch-time inputs, written to
//!   `inputs.tfvars.json` (mode 0600) beside the state, so the destroy reuses them, as Isoloom's
//!   CLI does. The launcher fills `PLAYER_CIDR` (this machine's public IP as a /32, for an
//!   allow-list) and `PLAYER_IP`, and the launch's own values (`CTF_API_URL`,
//!   `CTF_LAUNCH_TOKEN`); a lab asking for anything else can't start here.
//! - Every module may take `expires_at` (Unix seconds, for its tags) and `region`: passed as
//!   `TF_VAR_*`, which Terraform ignores for a module that doesn't declare them.
//! - On AWS, Terraform also gets shared credentials and config files of its own (see
//!   `AwsFiles`): labs that name a profile (CloudGoat's `profile = var.profile`, and
//!   `--profile` in its local-exec commands) find the picked account's keys under it, since an
//!   explicitly set profile beats the environment's keys in the AWS provider.
//! - What the lab exposes is its outputs (`cloud.outputs`), read from the state; its message
//!   names them (`{{ cloud.outputs.NAME }}`). Stop destroys everything: nothing is parked.

use std::path::{Path, PathBuf};

use isoloom_core::model::{CloudProvider, CloudServices};
use isoloom_core::{Spec, Target};
use serde_json::Value;

use crate::AppHandle;

use super::launch::{CLOUD_NEEDS_ACCOUNT, check_aws_budget, public_ip};
use super::paths::{lab_dir, record_host, record_runtime, state_dir};
use super::providers::Provider;
use super::{LabStatus, Output, Place, Runtime, lab, server, terraform};
use crate::error::{Error, Result};

/// The launch-time input the launcher fills with this machine's public IP as a /32.
pub const PLAYER_CIDR: &str = "PLAYER_CIDR";
/// The launch-time input the launcher fills with this machine's public IP.
pub const PLAYER_IP: &str = "PLAYER_IP";
/// Launch values a lab may also take as inputs (see `labs::run`).
const LAUNCH_INPUTS: [&str; 2] = ["CTF_API_URL", "CTF_LAUNCH_TOKEN"];
/// Beside the state: the launch-time inputs of the last apply, for the destroy.
const INPUTS_FILE: &str = "inputs.tfvars.json";

/// The lab's cloud services, or why it has none.
pub fn of(spec: &Spec) -> Result<&CloudServices> {
    spec.cloud.as_ref().ok_or_else(|| Error::Invalid("this lab's isoloom.yml declares no cloud services (`cloud:`)".into()))
}

/// The launcher's provider for a cloud.
pub fn provider(cloud: CloudProvider) -> Provider {
    match cloud {
        CloudProvider::Aws => Provider::Aws,
        CloudProvider::Azure => Provider::Azure,
        CloudProvider::Gcp => Provider::Gcp,
    }
}

/// The lab's module folder, inside the lab: a relative path that stays there.
pub fn module_dir(dir: &Path, cloud: &CloudServices) -> Result<PathBuf> {
    let rel = Path::new(cloud.terraform.trim().trim_end_matches('/'));
    if rel.as_os_str().is_empty() || !rel.components().all(|c| matches!(c, std::path::Component::Normal(_) | std::path::Component::CurDir)) {
        return Err(Error::Invalid(format!("this lab's Terraform module `{}` must be a folder inside the lab", cloud.terraform)));
    }
    Ok(dir.join(rel))
}

/// The variable files of a run: the spec's fixed values (generated by Isoloom), then the
/// launch-time inputs when the lab takes any.
pub fn var_files(dir: &Path, state: &Path) -> Vec<PathBuf> {
    let mut files = vec![lab::out(dir).join("cloud-services/terraform.tfvars.json")];
    let inputs = state.join(INPUTS_FILE);
    if inputs.is_file() {
        files.push(inputs);
    }
    files
}

/// The launch-time inputs the lab's variables take (`{{ inputs.NAME }}`), by input name.
fn wanted(cloud: &CloudServices) -> Vec<(&str, &str)> {
    cloud.vars.iter().filter_map(|(var, v)| CloudServices::input_of(v).map(|i| (var.as_str(), i))).collect()
}

/// Whether a launch needs this machine's public IP (an allow-list input).
pub fn needs_player_ip(cloud: &CloudServices) -> bool {
    wanted(cloud).iter().any(|(_, i)| *i == PLAYER_CIDR || *i == PLAYER_IP)
}

/// The values of the variables that take launch-time inputs, by variable name: from the launch
/// (`env`) or this machine's public IP. Every input must be known, or the module would be
/// applied with a hole in it.
pub fn inputs(cloud: &CloudServices, env: &[(String, String)], player_ip: Option<&str>) -> Result<serde_json::Map<String, Value>> {
    let mut values = serde_json::Map::new();
    let mut missing = Vec::new();
    for (var, input) in wanted(cloud) {
        let value = match input {
            PLAYER_CIDR => player_ip.map(|ip| format!("{ip}/32")),
            PLAYER_IP => player_ip.map(str::to_string),
            i if LAUNCH_INPUTS.contains(&i) => env.iter().find(|(k, _)| k == i).map(|(_, v)| v.clone()),
            _ => None,
        };
        match value.filter(|v| !v.is_empty()) {
            Some(v) => {
                values.insert(var.to_string(), Value::String(v));
            }
            None => missing.push(input.to_string()),
        }
    }
    if !missing.is_empty() {
        missing.dedup();
        return Err(Error::Invalid(format!(
            "This lab takes {} at launch, which the launcher can't provide (it fills {PLAYER_CIDR}, {PLAYER_IP}, CTF_API_URL and CTF_LAUNCH_TOKEN).",
            missing.join(", ")
        )));
    }
    Ok(values)
}

/// Writes the launch-time inputs beside the state (owner-only: they can hold a launch token),
/// or removes a previous run's when there are none.
pub fn write_inputs(state: &Path, values: &serde_json::Map<String, Value>) -> Result<()> {
    let file = state.join(INPUTS_FILE);
    if values.is_empty() {
        let _ = std::fs::remove_file(&file);
        return Ok(());
    }
    write_private(&file, &serde_json::to_string_pretty(&Value::Object(values.clone())).unwrap_or_default())
}

/// Writes a file only its owner can read (mode 0600 from creation, never wider), replacing any
/// previous one.
fn write_private(file: &Path, contents: &str) -> Result<()> {
    if let Some(parent) = file.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let _ = std::fs::remove_file(file);
    #[cfg(unix)]
    {
        use std::io::Write;
        use std::os::unix::fs::OpenOptionsExt;
        let mut f = std::fs::OpenOptions::new().write(true).create_new(true).mode(0o600).open(file)?;
        f.write_all(contents.as_bytes())?;
    }
    #[cfg(not(unix))]
    std::fs::write(file, contents)?;
    Ok(())
}

/// Terraform's own AWS shared files, beside the state.
const AWS_CREDENTIALS_FILE: &str = "aws-credentials";
const AWS_CONFIG_FILE: &str = "aws-config";

/// The AWS shared credentials and config files of one Terraform run: the picked account's keys
/// (stored AKIA keys, or the exported `aws login` session) as profile `default`, and under the
/// profile the lab names (`cloud.vars.profile`) when that is another one, with the account's
/// region. Written right before the run, owner-only, and removed when this is dropped (the run
/// over, failed or not), so session keys don't linger on disk.
pub struct AwsFiles {
    files: Vec<PathBuf>,
    pub env: Vec<(String, String)>,
}

impl AwsFiles {
    /// None when `env` holds no keys (an AWS CLI account without an exportable session: Terraform
    /// then reads the CLI's own files, as before).
    pub fn write(state: &Path, env: &[(String, String)], lab_profile: Option<&str>) -> Result<Option<AwsFiles>> {
        let get = |k: &str| env.iter().find(|(n, _)| n == k).map(|(_, v)| v.as_str()).filter(|v| !v.is_empty());
        let (Some(id), Some(secret)) = (get("AWS_ACCESS_KEY_ID"), get("AWS_SECRET_ACCESS_KEY")) else { return Ok(None) };
        let token = get("AWS_SESSION_TOKEN");
        let region = get("AWS_REGION").or(get("AWS_DEFAULT_REGION"));
        let mut profiles = vec!["default"];
        if let Some(p) = lab_profile.filter(|p| *p != "default" && valid_profile(p)) {
            profiles.push(p);
        }
        let (mut credentials, mut config) = (String::new(), String::new());
        for p in &profiles {
            credentials.push_str(&format!("[{p}]\naws_access_key_id = {id}\naws_secret_access_key = {secret}\n"));
            if let Some(t) = token {
                credentials.push_str(&format!("aws_session_token = {t}\n"));
            }
            config.push_str(&if *p == "default" { "[default]\n".to_string() } else { format!("[profile {p}]\n") });
            if let Some(r) = region {
                config.push_str(&format!("region = {r}\n"));
            }
        }
        let mut files = AwsFiles { files: vec![state.join(AWS_CREDENTIALS_FILE), state.join(AWS_CONFIG_FILE)], env: Vec::new() };
        write_private(&files.files[0], &credentials)?;
        write_private(&files.files[1], &config)?;
        files.env = vec![
            ("AWS_SHARED_CREDENTIALS_FILE".to_string(), files.files[0].display().to_string()),
            ("AWS_CONFIG_FILE".to_string(), files.files[1].display().to_string()),
        ];
        Ok(Some(files))
    }
}

impl Drop for AwsFiles {
    fn drop(&mut self) {
        for f in &self.files {
            let _ = std::fs::remove_file(f);
        }
    }
}

/// A profile name that can't break out of its `[...]` line.
fn valid_profile(p: &str) -> bool {
    !p.is_empty() && p.len() <= 64 && p.chars().all(|c| c.is_ascii_alphanumeric() || "-_.".contains(c))
}

/// The profile a lab's module names (`cloud.vars.profile`), if any.
fn lab_profile(cloud: &CloudServices) -> Option<&str> {
    cloud.vars.get("profile").and_then(Value::as_str)
}

/// The module's environment plus, on AWS, its own shared files (kept alive by the returned
/// guard for the length of the run).
async fn run_env(conn: &server::Connection, state: &Path, cloud: &CloudServices) -> Result<(Vec<(String, String)>, Option<AwsFiles>)> {
    let mut env = module_env(conn).await;
    let files = if conn.provider == Provider::Aws { AwsFiles::write(state, &env, lab_profile(cloud))? } else { None };
    if let Some(f) = &files {
        // The keys stay in the environment too; a CLI profile name would point outside the files.
        env.retain(|(k, _)| k != "AWS_PROFILE");
        env.extend(f.env.iter().cloned());
    }
    Ok((env, files))
}

/// Forgets the launch-time inputs once the lab is destroyed.
pub fn forget_inputs(state: &Path) {
    let _ = std::fs::remove_file(state.join(INPUTS_FILE));
}

/// The lab's outputs from the state, under the spec's names (strings as they are, anything else
/// as JSON). An output not in the state yet (not deployed, or the module lacks it) is left out.
pub fn outputs(cloud: &CloudServices, state: &Value) -> Vec<Output> {
    cloud
        .outputs
        .iter()
        .filter_map(|(name, output)| {
            let o = &state["outputs"][output];
            let v = &o["value"];
            if v.is_null() {
                return None;
            }
            let value = v.as_str().map(str::to_string).unwrap_or_else(|| v.to_string());
            Some(Output { name: name.clone(), value, sensitive: o["sensitive"].as_bool().unwrap_or(false) })
        })
        .collect()
}

/// The lab's message with its outputs filled in.
pub fn message(spec: &Spec, outputs: &[Output]) -> Option<String> {
    let map: indexmap::IndexMap<String, String> = outputs.iter().map(|o| (o.name.clone(), o.value.clone())).collect();
    spec.cloud_message(&map).map(|m| m.trim_end().to_string()).filter(|m| !m.is_empty())
}

/// The lab's status from its state: running while the state holds resources, none failed, and
/// its auto-stop time hasn't passed (the reaper then destroys it).
pub fn status(spec: &Spec, state_dir: &Path) -> LabStatus {
    let Some(state) = terraform::read_state(state_dir) else { return LabStatus::default() };
    let Ok(cloud) = of(spec) else { return LabStatus::default() };
    let expires_at = terraform::expires_at(state_dir);
    let expired = expires_at.is_some_and(|t| terraform::now() >= t);
    let up = terraform::has_resources(&state) && !expired;
    let outputs = if up { outputs(cloud, &state) } else { Vec::new() };
    LabStatus {
        running: up && !terraform::has_tainted(&state),
        expires_at: expires_at.filter(|_| up),
        message: if up { message(spec, &outputs) } else { None },
        outputs,
        place: Some(Place::Cloud),
        ..LabStatus::default()
    }
}

/// "About $0.02 an hour, $0.08 until it auto-stops in 4 h", for the log and the launch dialog.
pub fn cost_line(hourly_usd: Option<f64>, auto_stop_hours: u32) -> String {
    match hourly_usd {
        Some(h) if auto_stop_hours > 0 => format!(
            "Estimated cost: about ${h:.2} an hour, so about ${:.2} if it runs until it auto-stops in {auto_stop_hours} h (the lab's own estimate; your cloud bills the real amount).",
            h * f64::from(auto_stop_hours)
        ),
        Some(h) => format!("Estimated cost: about ${h:.2} an hour until you stop it (the lab's own estimate; your cloud bills the real amount)."),
        None => "This lab gives no cost estimate; your cloud bills what it creates until you stop it.".into(),
    }
}

/// A connection variable by name (`region`, `auto_stop_hours`, GCP's `project`).
fn var<'a>(vars: &'a [(String, String)], name: &str) -> Option<&'a str> {
    vars.iter().find(|(k, _)| k == name).map(|(_, v)| v.as_str())
}

/// The environment Terraform gets for the lab's module: the account's credentials, plus for
/// GCP the project and region the account runs labs in (the module's provider block may not
/// name them), and for AWS through the CLI, the CLI's session exported as keys (see
/// `aws_session`).
async fn module_env(conn: &server::Connection) -> Vec<(String, String)> {
    let mut env = conn.tf_env.clone();
    match conn.provider {
        Provider::Gcp => {
            if let Some(p) = var(&conn.tf_vars, "project") {
                env.push(("GOOGLE_PROJECT".into(), p.to_string()));
            }
            if let Some(r) = var(&conn.tf_vars, "region") {
                env.push(("GOOGLE_REGION".into(), r.to_string()));
            }
        }
        Provider::Aws if !env.iter().any(|(k, _)| k == "AWS_ACCESS_KEY_ID") => {
            let profile = env.iter().find(|(k, _)| k == "AWS_PROFILE").map(|(_, v)| v.clone());
            let session = aws_session(profile.as_deref()).await;
            if !session.is_empty() {
                env.retain(|(k, _)| k != "AWS_PROFILE");
                env.extend(session);
            }
        }
        _ => {}
    }
    env
}

/// Temporary keys from the AWS CLI's own session (`aws login`, SSO), for a lab module whose
/// AWS provider predates those sessions: nothing when the CLI has none. Never written down;
/// Terraform gets them in its environment, as Isoloom's CLI does.
async fn aws_session(profile: Option<&str>) -> Vec<(String, String)> {
    let mut args = vec!["configure", "export-credentials", "--format", "env-no-export"];
    if let Some(p) = profile {
        args.extend(["--profile", p]);
    }
    match crate::exec::run_read("aws", &args, None).await {
        Ok(out) => parse_session(&out),
        Err(_) => Vec::new(),
    }
}

/// `AWS_ACCESS_KEY_ID=...` lines (`env-no-export`), AWS_* only.
fn parse_session(out: &str) -> Vec<(String, String)> {
    out.lines()
        .filter_map(|l| l.trim().split_once('='))
        .filter(|(k, v)| k.starts_with("AWS_") && !v.is_empty())
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect()
}

/// Starts a cloud-services lab on the player's cloud account `host` (see the module).
pub(super) async fn start(app: &AppHandle, dir: &Path, id: &str, host: Option<&str>, env: &[(String, String)], log: &mut impl FnMut(String)) -> Result<()> {
    let host = host.ok_or_else(|| Error::Invalid(CLOUD_NEEDS_ACCOUNT.into()))?;
    let spec = lab::prepare(dir, Target::CloudServices)?;
    let cloud = of(&spec)?;
    let module = module_dir(dir, cloud)?;
    let conn = server::connection(app, host)?;
    check_account(cloud.provider, &conn)?;
    let state = state_dir(app, id, server::terraform_target(conn.provider).unwrap_or_default())?;
    if status(&spec, &state).running {
        return Err(Error::Invalid("This lab is already running in your cloud account. Stop it before starting it again.".into()));
    }
    let conn = ready_account(app, host, conn, log).await?;
    // Mark first, so a half-created lab can still be destroyed with the same account.
    server::mark_lab(dir, Some(host))?;
    log(format!("Running in your {} account {} ({})", conn.provider.id().to_uppercase(), conn.name, var(&conn.tf_vars, "region").unwrap_or("default region")));
    if conn.provider == Provider::Aws {
        check_aws_budget(app, host, log).await?;
    }
    let hours = auto_stop_hours(&conn);
    log(cost_line(cloud.hourly_usd, hours));
    let values = inputs(cloud, env, player_ip(cloud, log).await?.as_deref())?;
    std::fs::create_dir_all(&state)?;
    // For the auto-stop reaper, which destroys it with this account's credentials.
    record_runtime(&state, Runtime::Cloud)?;
    record_host(&state, host)?;
    write_inputs(&state, &values)?;
    let expires_at = (hours > 0).then(|| terraform::now() + u64::from(hours) * 3600);
    let (tf_env, aws_files) = run_env(&conn, &state, cloud).await?;
    log(format!("Creating the lab's cloud services ({})…", cloud.terraform));
    let applied = terraform::apply_services(&module, &state, &var_files(dir, &state), &launcher_vars(&conn, expires_at), expires_at, &tf_env, &mut *log).await;
    drop(aws_files);
    applied?;
    log_exposed(&status(&spec, &state), log);
    Ok(())
}

/// Refuses an account of another cloud than the lab's.
fn check_account(cloud: CloudProvider, conn: &server::Connection) -> Result<()> {
    if conn.provider == provider(cloud) {
        return Ok(());
    }
    let wanted = cloud.id().to_uppercase();
    Err(Error::Invalid(format!("This lab runs on {wanted}, and {} is a {} account. Pick a {wanted} account.", conn.name, conn.provider.id().to_uppercase())))
}

/// The account ready to run labs in: on GCP, its labs project made sure of (one free billing
/// slot), and the connection read again with it.
async fn ready_account(app: &AppHandle, host: &str, conn: server::Connection, log: &mut impl FnMut(String)) -> Result<server::Connection> {
    if conn.provider != Provider::Gcp {
        return Ok(conn);
    }
    log("Checking the Cyber CTF labs project on Google Cloud…".into());
    server::gcp::labs_project(app, host).await?;
    server::connection(app, host)
}

/// The account's auto-stop, in hours (0: none).
fn auto_stop_hours(conn: &server::Connection) -> u32 {
    var(&conn.tf_vars, "auto_stop_hours").and_then(|h| h.parse().ok()).unwrap_or(server::DEFAULT_AUTO_STOP_HOURS)
}

/// This machine's public IP when the lab lets only it in somewhere (an allow-list input).
async fn player_ip(cloud: &CloudServices, log: &mut impl FnMut(String)) -> Result<Option<String>> {
    if !needs_player_ip(cloud) {
        return Ok(None);
    }
    let ip = public_ip().await?;
    log(format!("Only your public IP ({ip}) is let in where the lab asks for an allow-list."));
    Ok(Some(ip))
}

/// The launcher's own variables (`TF_VAR_*`): when the lab ends, and the account's region.
fn launcher_vars(conn: &server::Connection, expires_at: Option<u64>) -> Vec<(String, String)> {
    let mut vars = vec![("expires_at".to_string(), expires_at.map(|t| t.to_string()).unwrap_or_default())];
    if let Some(r) = var(&conn.tf_vars, "region") {
        vars.push(("region".into(), r.to_string()));
    }
    vars
}

/// What the lab exposes, as the last lines of the deploy log (kept on disk): its non-secret
/// outputs, then its message with any secret it names masked.
fn log_exposed(s: &LabStatus, log: &mut impl FnMut(String)) {
    for o in s.outputs.iter().filter(|o| !o.sensitive) {
        log(format!("{}: {}", o.name, o.value));
    }
    if let Some(m) = &s.message {
        redact(m, &s.outputs).lines().for_each(|l| log(l.to_string()));
    }
}

/// `text` with the value of every sensitive output masked.
fn redact(text: &str, outputs: &[Output]) -> String {
    outputs.iter().filter(|o| o.sensitive && !o.value.is_empty()).fold(text.to_string(), |t, o| t.replace(&o.value, "••••••••"))
}

/// Destroys a cloud-services lab, ending what it costs.
pub(super) async fn destroy(app: &AppHandle, dir: &Path, id: &str, conn: &server::Connection, log: impl FnMut(String)) -> Result<()> {
    let tf = server::terraform_target(conn.provider).unwrap_or_default();
    let state = state_dir(app, id, tf)?;
    // The variable files again (a newer launcher, or a cleared output folder).
    let spec = lab::prepare(dir, Target::CloudServices)?;
    let cloud = of(&spec)?;
    let module = module_dir(dir, cloud)?;
    let (env, aws_files) = run_env(conn, &state, cloud).await?;
    let destroyed = terraform::destroy_services(&module, &state, &var_files(dir, &state), &env, log).await;
    drop(aws_files);
    destroyed?;
    forget_inputs(&state);
    Ok(())
}

/// The status of a cloud-services lab: from its state on the account it was started on.
pub(super) fn lab_status(app: &AppHandle, dir: &Path, id: &str, conn: Option<server::Connection>) -> Result<LabStatus> {
    let Some(conn) = conn else { return Ok(LabStatus::default()) };
    let tf = server::terraform_target(conn.provider).unwrap_or_default();
    let spec = lab::instanced(dir)?;
    let s = status(&spec, &state_dir(app, id, tf)?);
    Ok(LabStatus { host: Some(conn.name), provider: Some(conn.provider.id().to_string()), ..s })
}

/// What the launch dialog shows before a cloud-services lab starts: its cloud, what it costs
/// and what it asks for. Read from the lab's spec at its pinned commit.
#[derive(serde::Serialize, Debug, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct Preview {
    pub provider: String,
    pub hourly_usd: Option<f64>,
    /// The launch-time inputs it takes.
    pub inputs: Vec<String>,
    /// Whether it opens something to this machine's public IP only.
    pub allow_list: bool,
    /// The names of what it exposes once up.
    pub outputs: Vec<String>,
}

pub fn preview(spec: &Spec) -> Option<Preview> {
    let cloud = spec.cloud.as_ref()?;
    Some(Preview {
        provider: cloud.provider.id().to_string(),
        hourly_usd: cloud.hourly_usd,
        inputs: wanted(cloud).into_iter().map(|(_, i)| i.to_string()).collect(),
        allow_list: needs_player_ip(cloud),
        outputs: cloud.outputs.keys().cloned().collect(),
    })
}

/// [`Preview`] of a lab at a commit: the installed copy when it is that commit, else its
/// `isoloom.yml` from GitHub (CyberCTF repositories at a full SHA only).
pub async fn preview_at(app: &AppHandle, lab_id: &str, repository: &str, commit: &str) -> Result<Option<Preview>> {
    super::validate_id(lab_id)?;
    crate::labs::validate_source(repository, commit)?;
    if let Ok(dir) = lab_dir(app, lab_id)
        && std::fs::read_to_string(dir.join(".cyberctf-commit")).is_ok_and(|c| c.trim() == commit)
        && let Ok(spec) = isoloom_core::load(&dir)
    {
        return Ok(preview(&spec));
    }
    let url = format!("https://raw.githubusercontent.com/{repository}/{commit}/isoloom.yml");
    let client = reqwest::Client::builder().timeout(std::time::Duration::from_secs(10)).build().map_err(|e| Error::Invalid(e.to_string()))?;
    let res = client.get(&url).send().await.map_err(|e| Error::Invalid(format!("couldn't read the lab's spec: {e}")))?;
    if !res.status().is_success() {
        return Err(Error::Invalid(format!("couldn't read the lab's spec: HTTP {}", res.status())));
    }
    let text = res.text().await.map_err(|e| Error::Invalid(format!("couldn't read the lab's spec: {e}")))?;
    let spec = isoloom_core::parse(&text).map_err(|e| Error::Invalid(format!("this lab's isoloom.yml: {e}")))?;
    Ok(preview(&spec))
}

