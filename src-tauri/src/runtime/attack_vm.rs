        let vf = "config.vm.define \"a\" do |m|\n  m.vm.network \"private_network\", ip: \"10.0.0.5\", netmask: \"0.0.0.0\", virtualbox__intnet: \"isoloom-lab-n\"\n  v.name = \"lab · a\"\nend\n";
