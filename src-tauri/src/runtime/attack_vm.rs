/// The attacker's own Vagrant environment, inside the lab folder (removed with the lab).
const DIR: &str = ".cyberctf-attack-vm";
pub fn dir(lab_dir: &Path) -> PathBuf {
    lab_dir.join(DIR)
}

/// A Vagrant box reference the launcher accepts: `owner/name`, plain characters only (it goes
/// into a generated Vagrantfile and onto a command line).
pub fn valid_box(b: &str) -> bool {
    let ok = |s: &str| !s.is_empty() && s.len() <= 64 && s.chars().all(|c| c.is_ascii_alphanumeric() || "-_.".contains(c));
    matches!(b.split_once('/'), Some((owner, name)) if ok(owner) && ok(name))
}

/// One lab network the attacker joins: the lab's name for it, the hypervisor's internal-network
/// name, the attacker's (free) address on it, the netmask.
#[derive(Debug, PartialEq)]
pub(crate) struct Link {
    pub net: String,
    pub intnet: String,
    pub ip: Ipv4Addr,
    pub mask: Ipv4Addr,
}

/// Where the attacker sits in the lab, read from the lab's generated Vagrantfile: the lab's name
/// (the VM-name prefix) and one link per lab network, at an address no machine uses.
pub(crate) fn plan(lab_vagrantfile: &str) -> Result<(String, Vec<Link>)> {
    let lab = vm::vm_names_from(lab_vagrantfile)
        .first()
        .and_then(|n| n.split(" · ").next().map(str::to_string))
        .ok_or_else(|| Error::Invalid("the lab's Vagrantfile names no machine".into()))?;
    let (ifaces, networks) = vm::vagrant_topology(lab_vagrantfile, &lab);
    let mut links = Vec::new();
    for n in networks {
        let (base, len) = parse_cidr(&n.subnet).ok_or_else(|| Error::Invalid(format!("network `{}` has no subnet", n.name)))?;
        let used: HashSet<Ipv4Addr> = ifaces.values().flatten().filter(|i| i.network == n.name).filter_map(|i| i.ip.parse().ok()).collect();
        let ip = free_address(base, len, &used).ok_or_else(|| Error::Invalid(format!("no free address on `{}` for the attack VM", n.name)))?;
        links.push(Link { intnet: super::lab::vm_network(&lab, &n.name), net: n.name, ip, mask: mask_of(len) });
    }
    if links.is_empty() {
        return Err(Error::Invalid("the lab's Vagrantfile declares no network to join".into()));
    }
    Ok((lab, links))
}

fn parse_cidr(s: &str) -> Option<(Ipv4Addr, u8)> {
    let (ip, len) = s.split_once('/')?;
    let len: u8 = len.parse().ok()?;
    // A /0 (netmask 0.0.0.0) has no attacker address to pick, and sized the network with a
    // 32-bit shift that overflowed.
    (1..=30).contains(&len).then_some((ip.parse().ok()?, len))
}

fn mask_of(len: u8) -> Ipv4Addr {
    Ipv4Addr::from(if len == 0 { 0 } else { u32::MAX << (32 - len) })
}

/// The lowest host address from .2 (the gateway sits on .1) that no machine uses.
fn free_address(base: Ipv4Addr, len: u8, used: &HashSet<Ipv4Addr>) -> Option<Ipv4Addr> {
    let net = u32::from(base) & u32::from(mask_of(len));
    let size = 1u32 << (32 - len);
    (2..size - 1).map(|i| Ipv4Addr::from(net + i)).find(|a| !used.contains(a))
}

/// The attacker's Vagrantfile: one machine, the chosen box, NAT for the internet (the provider's
/// first adapter) and a NIC per lab network on the lab's internal networks.
pub(crate) fn vagrantfile(lab: &str, box_name: &str, links: &[Link], shared: Option<&Path>) -> String {
    let name = format!("{lab} · attacker");
    let mut out = format!(
        "# Generated by Cyber CTF: the attack VM beside the lab \"{lab}\". Don't edit: it is written at each start.\nVagrant.configure(\"2\") do |config|\n  config.vm.define \"attacker\" do |m|\n    m.vm.box = \"{box_name}\"\n    m.vm.hostname = \"attacker\"\n    m.vm.synced_folder \".\", \"/vagrant\", disabled: true\n    m.vm.boot_timeout = 900\n    # The provider's own NAT adapter (first NIC) gives it the internet, to install tools.\n"
    );
    // The folder shared with the attack box (Settings), at /shared inside it.
    if let Some(p) = shared {
        // A Ruby double-quoted string: `"`, `\` and `#` are escaped, or a folder named `#{...}`
        // (or one with a quote, from a hand-edited setting) would run as Ruby.
        let host = p.display().to_string().replace('\\', "\\\\").replace('"', "\\\"").replace('#', "\\#");
        out.push_str(&format!("    m.vm.synced_folder \"{host}\", \"{}\"\n", crate::shared_folder::MOUNT_POINT));
    }
    for l in links {
        out.push_str(&format!(
            "    m.vm.network \"private_network\", ip: \"{}\", netmask: \"{}\", virtualbox__intnet: \"{}\", libvirt__network_name: \"{}\", libvirt__dhcp_enabled: false\n",
            l.ip, l.mask, l.intnet, l.intnet
        ));
    }
    out.push_str(&format!(
        "    m.vm.provider \"virtualbox\" do |v|\n      v.name = \"{name}\"\n      v.memory = 2048\n      v.cpus = 2\n    end\n    m.vm.provider \"vmware_desktop\" do |v|\n      v.vmx[\"displayname\"] = \"{name}\"\n      v.vmx[\"memsize\"] = \"2048\"\n      v.vmx[\"numvcpus\"] = \"2\"\n    end\n    m.vm.provider \"parallels\" do |v|\n      v.name = \"{name}\"\n      v.memory = 2048\n      v.cpus = 2\n    end\n  end\nend\n"
    ));
    out
}

/// [`vagrantfile`] for `provider`. On Hyper-V the VM is attached to the virtual switch the
/// launcher picked (Vagrant would otherwise stop to ask, when there are several), and named.
fn vagrantfile_for(provider: Provider, lab: &str, box_name: &str, links: &[Link], shared: Option<&Path>) -> String {
    let out = vagrantfile(lab, box_name, links, shared);
    if provider != Provider::Hyperv {
        return out;
    }
    let body = out.strip_suffix("  end\nend\n").unwrap_or(&out);
    format!(
        "{body}{}    m.vm.provider \"hyperv\" do |v|\n      v.vmname = \"{lab} · attacker\"\n      v.memory = 2048\n      v.cpus = 2\n    end\n  end\nend\n",
        crate::exec::hyperv_switch_line("    ", "m")
    )
}

/// The folder shared with the attack VM, if it can be mounted on `provider`: on Hyper-V Vagrant
/// shares folders over SMB, which asks for a Windows password the launcher can't give, so none.
fn shared_for(provider: Provider, shared: Option<PathBuf>, log: &mut impl FnMut(String)) -> Option<PathBuf> {
    if provider == Provider::Hyperv && shared.is_some() {
        log(format!(
            "On Hyper-V the attack VM starts without the shared folder ({}): Vagrant would ask for a Windows password to share it.",
            crate::shared_folder::MOUNT_POINT
        ));
        return None;
    }
    shared
}

/// How many times a start that hit Vagrant's machine lock is tried again.
const LOCK_RETRIES: u32 = 4;

/// Starts the attacker beside the lab (whose Vagrantfile is in `lab_vagrant_dir`), on the same
/// hypervisor. The first start downloads the box.
pub async fn start(lab_dir: &Path, lab_vagrant_dir: &Path, provider: Provider, box_name: &str, mut log: impl FnMut(String)) -> Result<()> {
    if provider == Provider::Qemu {
        log(QEMU_ATTACKER.into());
        return Ok(());
    }
    if !valid_box(box_name) {
        return Err(Error::Invalid(format!("invalid attack VM box `{box_name}` (expected owner/name)")));
    }
    let text = std::fs::read_to_string(lab_vagrant_dir.join("Vagrantfile")).map_err(Error::Io)?;
    let (lab, links) = plan(&text)?;
    let d = dir(lab_dir);
    std::fs::create_dir_all(&d).map_err(Error::Io)?;
    let shared = shared_for(provider, crate::shared_folder::current(), &mut log);
    std::fs::write(d.join("Vagrantfile"), vagrantfile_for(provider, &lab, box_name, &links, shared.as_deref())).map_err(Error::Io)?;
    log(format!("Starting the attack VM ({box_name}) next to the lab; the first start downloads the box, which can take a while…"));
    vm::discard_aborted_saved(&d, &mut log).await;
    // Another Vagrant run touching the machine (a lab operation, a manual command) makes `up` fail
    // with "machine is locked" half-way: the VM then runs without its key swap or its lab network
    // card, and looks started. Wait for the lock and finish the boot sequence properly: `reload`
    // replays it (networks included) on a VM that exists; a plain second `up` would see it
    // running and do nothing.
    let mut args: Vec<&str> = vec!["up", "--provider", provider.id()];
    let vagrant = Vagrant::new(&d, &[], provider == Provider::Hyperv);
    for attempt in 1..=LOCK_RETRIES {
        let mut locked = false;
        let mut mount_failed = false;
        let result = vagrant
            .stream(&args, |line: String| {
                locked |= line.contains("because it is locked");
                // The box can't mount host folders (no guest additions / tools for this hypervisor).
                mount_failed |= ["vboxsf", "Guest Additions", "hgfs", "shared folder", "synced folder", "mount -t"].iter().any(|k| line.contains(k));
                log(line)
            })
            .await;
        match result {
            Ok(()) => break,
            Err(_) if mount_failed && shared.is_some() && attempt < LOCK_RETRIES => {
                log(format!("This attack VM can't mount the shared folder, so it starts without {}.", crate::shared_folder::MOUNT_POINT));
                std::fs::write(d.join("Vagrantfile"), vagrantfile_for(provider, &lab, box_name, &links, None)).map_err(Error::Io)?;
                args = vec!["reload", "--provision"];
            }
            Err(e) if attempt == LOCK_RETRIES => return Err(e),
            Err(_) if locked && attempt < LOCK_RETRIES => {
                log("Another Vagrant run is using this machine; finishing the start when it's done…".into());
                tokio::time::sleep(std::time::Duration::from_secs(20)).await;
                args = vec!["reload", "--provision"];
            }
            Err(e) if args[0] == "reload" && attempt < LOCK_RETRIES && e.to_string().contains("not created") => {
                args = vec!["up", "--provider", provider.id()];
            }
            Err(e) => return Err(e),
        }
    }
    log("Attack VM ready.".into());
    Ok(())
}

/// Destroys the attacker, finishing at the hypervisor by its exact VM name (as for the lab's
/// own VMs). Nothing to do when it was never started. Vagrant's record of it (`.vagrant`) goes
/// only once the destroy succeeded: on VMware, Hyper-V or libvirt nothing else can find the VM
/// again, so a failed destroy keeps it, and says so, for the next stop to retry.
pub async fn stop(lab_dir: &Path, mut log: impl FnMut(String)) -> Result<()> {
    let d = dir(lab_dir);
    if !d.join("Vagrantfile").exists() {
        return Ok(());
    }
    log("Removing the attack VM…".into());
    let destroyed = Vagrant::of(&d, &[]).stream(&["destroy", "--force"], &mut log).await;
    let names: HashSet<String> = vm::vm_names(&d).into_iter().collect();
    if !names.is_empty() {
        vm::recover_virtualbox(&names, &mut log).await;
        vm::recover_parallels(&names, &mut log).await;
    }
    destroyed.map_err(|e| Error::Invalid(format!("The attack VM wasn't removed: {e}")))?;
    let _ = std::fs::remove_dir_all(d.join(".vagrant"));
    Ok(())
}

/// Parks the attacker with the lab (nothing to do when it was never started).
pub async fn park(lab_dir: &Path, mode: Park, log: impl FnMut(String)) -> Result<()> {
    let d = dir(lab_dir);
    if !d.join("Vagrantfile").exists() {
        return Ok(());
    }
    vm::park(&d, mode, &[], log).await
}

/// Brings a parked attacker back with the lab.
pub async fn resume(lab_dir: &Path, log: impl FnMut(String)) -> Result<()> {
    let d = dir(lab_dir);
    if !d.join("Vagrantfile").exists() {
        return Ok(());
    }
    vm::resume(&d, &[], log).await
}

/// The attacker's status, in the container attack box's shape: `image_present` is the box being
/// downloaded already, `ip`/`lab_network` its first lab address once running. On QEMU, the
/// controller's; a read that fails there is an error, not a stopped attacker.
pub async fn status(lab_dir: &Path, box_name: &str) -> Result<ExegolStatus> {
    let lab = super::lab::vagrant_dir(lab_dir, super::Runtime::Vm);
    if vm::on_qemu(&lab) {
        return controller_status(&lab).await;
    }
    Ok(own_status(lab_dir, box_name).await)
}

async fn own_status(lab_dir: &Path, box_name: &str) -> ExegolStatus {
    let d = dir(lab_dir);
    let image_present = run_read("vagrant", &["box", "list"], None).await.map(|out| box_listed(&out, box_name)).unwrap_or(false);
    let status = if d.join("Vagrantfile").exists() { vm::status(&d, &[]).await.ok() } else { None };
    own_view(&d, image_present, status)
}

/// Whether `vagrant box list` output lists `box_name`.
fn box_listed(out: &str, box_name: &str) -> bool {
    out.lines().any(|l| l.split_whitespace().next() == Some(box_name))
}

/// The attacker's status from its own folder's VM status (None: never started, or unreadable).
fn own_view(d: &Path, image_present: bool, status: Option<super::LabStatus>) -> ExegolStatus {
    let (running, ip, lab_network) = match status {
        Some(s) => {
            let first = s.machines.into_iter().next();
            let ip = first.as_ref().map(|m| m.ip.clone()).unwrap_or_default();
            let net = first.and_then(|m| m.interfaces.into_iter().next()).map(|i| i.network).unwrap_or_default();
            (s.running, if s.running { ip } else { String::new() }, if s.running { net } else { String::new() })
        }
        None => (false, String::new(), String::new()),
    };
    ExegolStatus { image_present, running, ip, lab_network, shell_cmd: shell_line(d, None, false, cfg!(windows)) }
}

/// On QEMU, the lab's network links two VMs: no room for an attack VM.
pub const QEMU_ATTACKER: &str = "On QEMU, the lab network links exactly two VMs, so there is no attack VM: attack from the lab's controller (Debian, on the lab network), which stays on. Open its shell from the lab page.";

/// The controller standing in for the attacker on QEMU, in the same status shape.
async fn controller_status(lab_vagrant_dir: &Path) -> Result<ExegolStatus> {
    Ok(controller_view(lab_vagrant_dir, vm::status(lab_vagrant_dir, &[]).await?.machines))
}

/// The controller's status, in the attacker's shape, from the lab's machines.
fn controller_view(lab_vagrant_dir: &Path, machines: Vec<super::Machine>) -> ExegolStatus {
    let controller = machines.into_iter().find(|m| m.name == vm::CONTROLLER);
    let running = controller.as_ref().is_some_and(|m| m.state == "running");
    let (ip, lab_network) = match controller.filter(|_| running) {
        Some(m) => (m.ip.clone(), m.interfaces.into_iter().next().map(|i| i.network).unwrap_or_default()),
        None => (String::new(), String::new()),
    };
    ExegolStatus { image_present: true, running, ip, lab_network, shell_cmd: shell_line(lab_vagrant_dir, Some(vm::CONTROLLER), false, cfg!(windows)) }
}

/// Where the attack VM's shell is: the Vagrant folder `vagrant ssh` runs in, and the machine to
/// reach there (None: the folder's only one). On QEMU, the lab's controller.
pub fn shell_target(lab_dir: &Path) -> Result<(PathBuf, Option<&'static str>)> {
    let lab = super::lab::vagrant_dir(lab_dir, super::Runtime::Vm);
    if vm::on_qemu(&lab) {
        return Ok((lab, Some(vm::CONTROLLER)));
    }
    let d = dir(lab_dir);
    if !d.join("Vagrantfile").exists() {
        return Err(Error::Invalid("the attack VM isn't started".into()));
    }
    Ok((d, None))
}

/// `vagrant ssh [machine]` from the folder `d`, as a command line: POSIX shell (`exec` replacing
/// the shell when `exec`), or cmd.exe on Windows, which has no `sh` and no single quotes
/// (Windows paths can't hold a `"`, so double quotes are enough there).
fn shell_line(d: &Path, machine: Option<&str>, exec: bool, windows: bool) -> String {
    let ssh = match machine {
        Some(m) => format!("vagrant ssh {m}"),
        None => "vagrant ssh".to_string(),
    };
    if windows {
        format!("cd /d \"{}\" && {ssh}", d.display())
    } else {
        format!("cd {} && {}{ssh}", ssh::sh_quote(&d.to_string_lossy()), if exec { "exec " } else { "" })
    }
}

/// The command line that opens the attack VM's shell: `sh -c 'cd … && exec vagrant ssh'` on
/// macOS and Linux, `cd /d "…" && vagrant ssh` for cmd.exe on Windows.
pub fn shell_command(lab_dir: &Path) -> Result<String> {
    let (d, machine) = shell_target(lab_dir)?;
    Ok(platform_shell_command(&d, machine, cfg!(windows)))
}

fn platform_shell_command(d: &Path, machine: Option<&str>, windows: bool) -> String {
    if windows { shell_line(d, machine, false, true) } else { format!("sh -c {}", ssh::sh_quote(&shell_line(d, machine, true, false))) }
}

/// Opens the player's terminal on an SSH session into the attacker.
pub fn shell(lab_dir: &Path) -> Result<()> {
    #[cfg(windows)]
    return exegol::open_terminal_cmd(&shell_command(lab_dir)?);
    #[cfg(not(windows))]
    exegol::open_terminal(&shell_command(lab_dir)?)
}

