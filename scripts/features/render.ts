// tests/FEATURES.md, made from the registry and the rig's snapshot: the biggest gaps, then a table
// per area (a row a feature, a mark a tier, the rig, the level), what each partial tier leaves
// out, and the tests themselves. Markdown only; main.ts formats it as Prettier would.
import { slug } from "../check/doc-links.ts";
import { biggestGaps, level, levelCounts, mark, type Mark } from "./coverage.ts";
import { rigState, type RigSnapshot } from "./matrix.ts";
import { features, PLATFORMS, TIERS, type Area, type Feature, type Platform, type Registry, type Tier } from "./registry.ts";

/** How many gaps the top list holds. */
const TOP_GAPS = 15;

const MARK: Record<Mark, string> = { covered: "✔", partial: "◐", none: "✖" };
const TIER_TITLE: Record<Tier, string> = {
  unit: "Unit",
  web: "Web E2E",
  desktop: "Desktop E2E",
  integration: "Integration",
  setup: "Setup",
  package: "Package",
};
const PLATFORM_TITLE: Record<Platform, string> = { linux: "Linux", macos: "macOS", windows: "Windows" };
const RIG_MARK = { pass: "✅", fail: "❌", skip: "⏭", notrun: "·", none: "–" } as const;

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const code = (s: string) => `\`${s.replace(/`/g, "'")}\``;
const platforms = (f: Feature) => (f.platforms.length === PLATFORMS.length ? "all" : f.platforms.map((p) => PLATFORM_TITLE[p]).join(", "));

function rigCell(f: Feature, rig: RigSnapshot): string {
  if (!f.rig.length) return "–";
  return f.platforms.map((p) => `${PLATFORM_TITLE[p]} ${RIG_MARK[rigState(rig, f.rig, p)]}`).join(", ");
}

function row(f: Feature, rig: RigSnapshot): string {
  const marks = TIERS.map((t) => MARK[mark(f, t)]);
  return `| ${code(f.id)} ${cell(f.what)} | ${platforms(f)} | ${marks.join(" | ")} | ${rigCell(f, rig)} | **${level(f, rig)}** |`;
}

/** The lines saying what each partial or missing tier of the area's features leaves out. */
function missing(area: Area): string[] {
  return area.features.flatMap((f) => {
    const parts = TIERS.filter((t) => f.gaps[t]).map((t) => `${TIER_TITLE[t]} ${MARK[mark(f, t)]} ${f.gaps[t] ?? ""}`);
    if (f.note) parts.push(f.note);
    return parts.length ? [`- ${code(f.id)}: ${parts.map(cell).join("; ")}`] : [];
  });
}

/** One feature's tests, tier by tier, and the rig columns that run it. */
function testsLine(f: Feature): string {
  const tiers = TIERS.filter((t) => f.tests[t].length).map((t) => `${TIER_TITLE[t]}: ${f.tests[t].map(code).join(", ")}`);
  if (f.rig.length) tiers.push(`Rig: ${f.rig.map(code).join(", ")}`);
  const where = [platforms(f) === "all" ? "" : platforms(f), f.providers.join(", ")].filter(Boolean).join("; ");
  return `- ${code(f.id)}${where ? ` (${where})` : ""}: ${tiers.length ? tiers.join(". ") : "no test"}.`;
}

function areaSection(area: Area, rig: RigSnapshot): string[] {
  const n = levelCounts(area.features, rig);
  return [
    `## ${area.title}`,
    "",
    `${String(area.features.length)} features: ${String(n.Strong)} Strong, ${String(n.Partial)} Partial, ${String(n.Unchecked)} Unchecked.`,
    "",
    `| Feature | Platforms | ${TIERS.map((t) => TIER_TITLE[t]).join(" | ")} | Rig | Level |`,
    `| --- | --- | ${TIERS.map(() => "---").join(" | ")} | --- | --- |`,
    ...area.features.map((f) => row(f, rig)),
    "",
    ...(missing(area).length ? ["What the partial and missing tiers leave out:", "", ...missing(area), ""] : []),
    "<details><summary>The tests</summary>",
    "",
    ...area.features.map(testsLine),
    "",
    "</details>",
    "",
  ];
}

function gapLines(registry: Registry, rig: RigSnapshot): string[] {
  return biggestGaps(registry, rig, TOP_GAPS).map((g, i) => {
    const shown = g.features.slice(0, 6).map(code).join(", ");
    if (!g.features.length)
      return `${String(i + 1)}. ${code(g.title.split(": ")[0])}: **${cell(g.title.split(": ").slice(1).join(": "))}**${g.detail ? `: ${cell(g.detail)}` : ""}`;
    const more = g.features.length > 6 ? ` and ${String(g.features.length - 6)} more` : "";
    return `${String(i + 1)}. **${cell(g.title)}**${g.detail ? `: ${cell(g.detail)}` : ""}${shown ? ` (${shown}${more})` : ""}`;
  });
}

function summaryTable(registry: Registry, rig: RigSnapshot): string[] {
  return [
    "| Area | Features | Strong | Partial | Unchecked |",
    "| --- | --- | --- | --- | --- |",
    ...registry.areas.map((a) => {
      const n = levelCounts(a.features, rig);
      return `| [${a.title}](#${slug(a.title)}) | ${String(a.features.length)} | ${String(n.Strong)} | ${String(n.Partial)} | ${String(n.Unchecked)} |`;
    }),
  ];
}

/** FEATURES.md for `registry`, its rig columns read from `rig`. */
export function render(registry: Registry, rig: RigSnapshot): string {
  const all = features(registry);
  const n = levelCounts(all, rig);
  return [
    "# Features and their tests",
    "",
    "<!-- Generated by scripts/features/main.ts from tests/features.yml and tests/features-rig.json: don't edit it by hand. `pnpm features` writes it; `pnpm check:features` fails when it is stale. -->",
    "",
    "Every feature the launcher offers its user, area by area, and how well each test tier checks it. The registry is",
    "[features.yml](features.yml); [README.md](README.md#the-feature-registry) says how a feature or a test is added.",
    "",
    `**${String(all.length)} features: ${String(n.Strong)} Strong, ${String(n.Partial)} Partial, ${String(n.Unchecked)} Unchecked.**`,
    "",
    "- A tier: ✔ its tests check the feature's behaviour; ◐ they check part of it (what is missing is under the table); ✖ no test.",
    "- **Strong**: unit tests, and a tier above that covers it: a real-host one (desktop E2E, integration, setup, package) when the feature depends on the",
    "  machine, any end-to-end one otherwise; and, for a feature the rig runs, one of its rig cells passed. **Unchecked**: no test at all.",
    "  **Partial**: everything between.",
    `- Rig: how the cells of the workspace's test rig that run the feature last went on each of its platforms (rig/MATRIX.md, generated ${rig.generated || "never"}):`,
    "  ✅ passed, ❌ failed, ⏭ skipped, · never run, – no such cell. A reference `vm@qemu` is the VMs column of the rows readied for QEMU. The rig's",
    "  `repos` cell runs every unit and web test, so no feature lists it.",
    "",
    "## Biggest gaps",
    "",
    ...(gapLines(registry, rig).length ? gapLines(registry, rig) : ["None."]),
    "",
    "## By area",
    "",
    ...summaryTable(registry, rig),
    "",
    ...registry.areas.flatMap((a) => areaSection(a, rig)),
  ].join("\n");
}
